function req_check(): array {
    return [
        ['PHP 8.1+',           version_compare(PHP_VERSION, '8.1.0', '>=')],
        ['PDO Extension',      extension_loaded('pdo')],
        ['PDO MySQL',          extension_loaded('pdo_mysql')],
        ['OpenSSL',            extension_loaded('openssl')],
        ['Fileinfo',           extension_loaded('fileinfo')],
        ['Mbstring',           extension_loaded('mbstring')],
        ['config/ writable',   is_writable(dirname(__DIR__) . '/config')],
        ['uploads/ writable',  is_writable(dirname(__DIR__) . '/uploads')],
    ];
}

function test_db(string $host, string $user, string $pass, string $db): bool|string {
    try {
        $pdo = new PDO(
            "mysql:host={$host};charset=utf8mb4",
            $user, $pass,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$db}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        return true;
    } catch (PDOException $e) {
        return $e->getMessage();
    }
}

function run_sql(string $host, string $user, string $pass, string $db, string $sql_file): bool|string {
    try {
        $pdo = new PDO(
            "mysql:host={$host};dbname={$db};charset=utf8mb4",
            $user, $pass,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );
        $sql = file_get_contents($sql_file);
        // Strip CREATE DATABASE / USE statements so we use our db
        $sql = preg_replace('/^(CREATE DATABASE|USE)\s+[^;]+;/im', '', $sql);
        $pdo->exec($sql);
        return true;
    } catch (PDOException $e) {
        return $e->getMessage();
    }
}

